    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        // TODO add your handling code here:
                                     
    String idGuru = txtIdGuru.getText();
    String nama = txtNama.getText();
    String kelas = cmbKelas.getSelectedItem().toString();

    // Mengecek apakah input kosong
    if (idGuru.isEmpty() || nama.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Id Guru dan Nama harus diisi!");

        return;
    }

    // Mengambil tanggal hari ini
    String tanggal = new SimpleDateFormat("dd-MM-yyyy").format(new Date());

    // Memasukkan data ke tabel
    model.addRow(new Object[]{
        idGuru,
        nama,
        kelas,
        tanggal
    });

    // Mengosongkan input
    txtIdGuru.setText("");
    txtNama.setText("");
    cmbKelas.setSelectedIndex(0);

    JOptionPane.showMessageDialog(this,
            "Data Wali Kelas berhasil ditambahkan!");
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:                            
    int baris = tblDataGuru.getSelectedRow();

    // Mengecek apakah ada data yang dipilih
    if (baris == -1) {
        JOptionPane.showMessageDialog(this,
                "Pilih data yang ingin dihapus!");

        return;
    }

    // Konfirmasi sebelum menghapus
    int konfirmasi = JOptionPane.showConfirmDialog(
            this,
            "Apakah yakin ingin menghapus data ini?",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION
    );

    if (konfirmasi == JOptionPane.YES_OPTION) {

        model.removeRow(baris);

        // Mengosongkan input
        txtIdGuru.setText("");
        txtNama.setText("");
        cmbKelas.setSelectedIndex(0);

        JOptionPane.showMessageDialog(this,
                "Data berhasil dihapus!");
    }
    }//GEN-LAST:event_btnHapusActionPerformed

